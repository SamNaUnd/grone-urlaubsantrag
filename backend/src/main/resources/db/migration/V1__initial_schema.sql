CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('TRAINEE', 'INSTRUCTOR', 'ADMIN')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    credentials_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE trainees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    training_program VARCHAR(150) NOT NULL,
    instructor_id BIGINT NOT NULL REFERENCES users(id),
    training_location VARCHAR(150) NOT NULL DEFAULT 'Berlin',
    federal_state VARCHAR(5) NOT NULL DEFAULT 'DE-BE'
);

CREATE TABLE leave_entitlements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainee_id BIGINT NOT NULL REFERENCES trainees(id),
    leave_year INTEGER NOT NULL CHECK (leave_year BETWEEN 2020 AND 2100),
    days INTEGER NOT NULL CHECK (days BETWEEN 0 AND 366),
    UNIQUE (trainee_id, leave_year)
);

CREATE TABLE leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainee_id BIGINT NOT NULL REFERENCES trainees(id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL CHECK (end_date >= start_date),
    total_days INTEGER NOT NULL CHECK (total_days > 0),
    reason VARCHAR(2000) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN', 'APPROVED', 'REJECTED', 'WITHDRAWN')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_leave_requests_trainee_dates ON leave_requests(trainee_id, start_date, end_date);

CREATE TABLE approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leave_request_id BIGINT NOT NULL UNIQUE REFERENCES leave_requests(id),
    approver_id BIGINT NOT NULL REFERENCES users(id),
    decision VARCHAR(20) NOT NULL CHECK (decision IN ('APPROVED', 'REJECTED')),
    comment VARCHAR(2000) NOT NULL DEFAULT '',
    decision_date TIMESTAMP WITH TIME ZONE NOT NULL
);
