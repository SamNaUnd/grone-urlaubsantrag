CREATE TABLE registration_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash VARCHAR(64) NOT NULL UNIQUE,
    role VARCHAR(20) NOT NULL CHECK (role IN ('INSTRUCTOR', 'TRAINEE')),
    training_program VARCHAR(150),
    instructor_id BIGINT REFERENCES users(id),
    entitlement_year INTEGER NOT NULL CHECK (entitlement_year BETWEEN 2020 AND 2100),
    entitlement_days INTEGER NOT NULL CHECK (entitlement_days BETWEEN 0 AND 366),
    created_by_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    redeemed_at TIMESTAMP WITH TIME ZONE,
    revoked_at TIMESTAMP WITH TIME ZONE,
    CHECK (role <> 'TRAINEE' OR (instructor_id IS NOT NULL AND training_program IS NOT NULL))
);
